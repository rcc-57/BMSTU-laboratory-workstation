#ifndef E502_CTRL_H
#define E502_CTRL_H

#include <stdint.h>
#include <stdbool.h>
#include "x502api.h"
#include "e502api.h"

#define STAND_MAX_CHANNELS 32 /* Ограничение для удобства отображения на стенде (API поддерживает до 256) */
#define E502_STAND_MAGIC   0x45353032U /* Сигнатура инициализированной структуры ('E502') */

/* Структура настроек одного логического канала для контроля состояния */
typedef struct {
    uint32_t phy_ch;   /* Физический канал: 0..15 (дифф) или 0..31 (общая земля) */
    uint32_t mode;     /* Режим измерения (t_x502_lch_mode, например X502_LCH_MODE_COMM) */
    uint32_t range;    /* Диапазон измерения (t_x502_adc_range, например X502_ADC_RANGE_10) */
    uint32_t avg;      /* Коэффициент усреднения (0 - по умолчанию, 1..X502_LCH_AVG_SIZE_MAX) */
} E502_ChannelConfig;

/* Полный контекст устройства для стенда (используется и в консоли, и в UI) */
typedef struct {
    t_x502_hnd hnd;                                  /* Описатель модуля L-Card */
    t_x502_info dev_info;                            /* Постоянная информация о модуле */
    bool is_connected;                               /* Статус соединения */
    bool config_dirty;                               /* Флаг: настройки изменены, но еще не переданы через X502_Configure */
    uint32_t lch_count;                              /* Количество активных логических каналов */
    E502_ChannelConfig lch_cfg[STAND_MAX_CHANNELS];  /* Текущая конфигурация логической таблицы */
    uint32_t pullups_mask;                           /* Маска подтягивающих резисторов */
    double dac_volts[2];                             /* Последние установленные напряжения на ЦАП1 и ЦАП2 */
    int32_t last_error;                              /* Код последней ошибки библиотеки */
    uint32_t init_magic;                             /* Маркер инициализации для защиты от мусора на стеке */
} E502_StandDevice;

/* ============================================================================
 * 1. Инициализация структуры и управление соединением с модулем E-502
 * ============================================================================ */

/**
 * @brief Безопасно инициализирует структуру контекста устройства значениями по умолчанию.
 *
 * Если структура уже была инициализирована ранее (init_magic == E502_STAND_MAGIC) и содержит
 * открытый дескриптор (hnd != NULL), функция автоматически вызывает E502_StandDisconnect(dev)
 * для предотвращения утечки ресурсов перед сбросом полей.
 * После вызова: lch_count = 4, все 32 канала настроены в режим X502_LCH_MODE_COMM на диапазон
 * X502_ADC_RANGE_10 (+/-10 В) без усреднения, маска подтяжки pullups_mask = X502_PULLUP_DI_SYN1 (0x04),
 * флаг config_dirty = true.
 *
 * @param[in,out] dev  Указатель на структуру контекста стенда (при NULL вызов безопасно игнорируется).
 */
void E502_StandInitStruct(E502_StandDevice *dev);

/**
 * @brief Сканирует шину USB и получает список серийных номеров подключённых модулей E-502.
 *
 * @param[out] serials      Двумерный массив строк [max_count][X502_SERIAL_SIZE] для записи
 *                          нуль-терминированных серийных номеров найденных приборов (не NULL при max_count > 0).
 * @param[in]  max_count    Максимальное число серийных номеров, вмещаемое массивом serials (размер буфера).
 * @param[out] found_count  Указатель, по которому записывается фактическое количество обнаруженных модулей
 *                          (может быть NULL, если общее число не требуется).
 * @return X502_ERR_OK (0) при успешном опросе шины, либо отрицательный код ошибки X502_ERR_*.
 */
int E502_StandListUSB(char serials[][X502_SERIAL_SIZE], uint32_t max_count, uint32_t *found_count);

/**
 * @brief Открывает соединение с модулем E-502 по интерфейсу USB 2.0 и применяет начальную конфигурацию ПЛИС.
 *
 * Создаёт дескриптор X502_Create(), открывает прибор через E502_OpenUsb(), считывает паспортные данные
 * X502_GetDevInfo() в dev->dev_info и вызывает E502_StandApplyConfig(). При наличии ранее открытого
 * соединения автоматически закрывает его перед повторным подключением. При сбое на любом этапе
 * гарантированно освобождает дескриптор.
 *
 * @param[in,out] dev     Указатель на контекст устройства (не NULL).
 * @param[in]     serial  Строка с серийным номером целевого модуля. Если передан NULL или пустая строка "",
 *                        выполняется автоматический поиск и подключение к первому найденному модулю на шине USB.
 * @return X502_ERR_OK (0) при успешном подключении, X502_ERR_DEVICE_NOT_FOUND (-5) если приборы не найдены,
 *         либо иной отрицательный код ошибки X502_ERR_*.
 */
int E502_StandConnectUSB(E502_StandDevice *dev, const char *serial);

/**
 * @brief Открывает сетевое соединение с модулем E-502 по интерфейсу Ethernet (TCP/IP) и настраивает ПЛИС.
 *
 * Создаёт дескриптор X502_Create(), устанавливает связь через E502_OpenByIpAddr(), заполняет dev->dev_info
 * и синхронизирует настройки с регистрами ПЛИС через E502_StandApplyConfig().
 *
 * @param[in,out] dev      Указатель на контекст устройства (не NULL).
 * @param[in]     ip_addr  IPv4-адрес прибора в хост-порядке байт (например, для 192.168.1.100:
 *                         (192U << 24) | (168U << 16) | (1U << 8) | 100U = 0xC0A80164). Не должен быть равен 0.
 * @param[in]     tout_ms  Таймаут ожидания установки TCP-соединения в миллисекундах (рекомендуется 500..5000 мс).
 * @return X502_ERR_OK (0) при успешном подключении, либо отрицательный код ошибки X502_ERR_*.
 */
int E502_StandConnectIP(E502_StandDevice *dev, uint32_t ip_addr, uint32_t tout_ms);

/**
 * @brief Закрывает соединение с модулем и освобождает системный дескриптор t_x502_hnd.
 *
 * Вызывает X502_Close() и X502_Free(), обнуляет dev->hnd = NULL и сбрасывает dev->is_connected = false.
 * Функция идемпотентна: повторный вызов для уже отключённого устройства безопасен.
 *
 * @param[in,out] dev  Указатель на контекст устройства (при NULL вызов игнорируется).
 */
void E502_StandDisconnect(E502_StandDevice *dev);


/* ============================================================================
 * 2. Настройка логической таблицы АЦП и транзакционная запись в ПЛИС (FPGA)
 * ============================================================================ */

/**
 * @brief Задаёт количество активных логических каналов в таблице опроса АЦП.
 *
 * Изменяет значение dev->lch_count в теневой конфигурации и выставляет флаг dev->config_dirty = true.
 * Для фактической передачи изменений в аппаратуру необходимо вызвать E502_StandApplyConfig(dev)
 * (или E502_StandReadAdcFrame, который применит изменения автоматически).
 *
 * @param[in,out] dev    Указатель на контекст устройства (не NULL).
 * @param[in]     count  Количество опрашиваемых логических каналов. Допустимый диапазон: 1..STAND_MAX_CHANNELS (1..32).
 * @return X502_ERR_OK (0) при успехе, либо X502_ERR_INVALID_LTABLE_SIZE (-102) при выходе count за пределы 1..32.
 */
int E502_StandSetChannelCount(E502_StandDevice *dev, uint32_t count);

/**
 * @brief Настраивает параметры одного слота логической таблицы АЦП (с проверкой границ и совместимости).
 *
 * Проверяет корректность индекса логического канала, режима измерения, номера физического входа,
 * входного диапазона АЦП и коэффициента усреднения. Сохраняет параметры в dev->lch_cfg[lch]
 * и устанавливает флаг dev->config_dirty = true.
 *
 * @param[in,out] dev     Указатель на контекст устройства (не NULL).
 * @param[in]     lch     Индекс настраиваемого логического канала: 0 .. (dev->lch_count - 1), но не более 31.
 * @param[in]     phy_ch  Номер физического аналогового входа АЦП:
 *                        - для режима X502_LCH_MODE_COMM: допустимы входы 0..31 (измерение относительно AGND);
 *                        - для режима X502_LCH_MODE_DIFF: допустимы входы 0..15 (разность между phy_ch и phy_ch + 16);
 *                        - для режима X502_LCH_MODE_ZERO: должен быть < 32 (обычно 0, измерение собственного нуля).
 * @param[in]     mode    Режим подключения входа из перечисления t_x502_lch_mode:
 *                        - X502_LCH_MODE_COMM (0) — общая земля;
 *                        - X502_LCH_MODE_DIFF (1) — дифференциальный вход;
 *                        - X502_LCH_MODE_ZERO (2) — калибровка нуля.
 * @param[in]     range   Код поддиапазона входного напряжения из перечисления t_x502_adc_range:
 *                        - X502_ADC_RANGE_10 (0) — +/-10 В;
 *                        - X502_ADC_RANGE_5  (1) — +/-5 В;
 *                        - X502_ADC_RANGE_2  (2) — +/-2 В;
 *                        - X502_ADC_RANGE_1  (3) — +/-1 В;
 *                        - X502_ADC_RANGE_05 (4) — +/-0.5 В;
 *                        - X502_ADC_RANGE_02 (5) — +/-0.2 В.
 * @param[in]     avg     Коэффициент аппаратного усреднения отсчётов в ПЛИС: 0 (по умолчанию = 1) или 1..128.
 *                        Снижает СКО случайного шума в sqrt(avg) раз.
 * @return X502_ERR_OK (0) при успехе, либо код ошибки валидации:
 *         X502_ERR_INVALID_LCH_NUMBER (-103), X502_ERR_INVALID_LCH_MODE (-105),
 *         X502_ERR_INVALID_LCH_PHY_NUMBER (-106), X502_ERR_INVALID_LCH_RANGE (-104),
 *         X502_ERR_INVALID_LCH_AVG_SIZE (-107).
 */
int E502_StandConfigChannel(E502_StandDevice *dev, uint32_t lch, uint32_t phy_ch,
                            uint32_t mode, uint32_t range, uint32_t avg);

/**
 * @brief Задаёт битовую маску нагрузочных резисторов подтяжки (pull-up / pull-down) цифровых входов.
 *
 * Сохраняет маску в dev->pullups_mask и выставляет флаг dev->config_dirty = true.
 *
 * @param[in,out] dev           Указатель на контекст устройства (не NULL).
 * @param[in]     pullups_mask  Битовая маска подтяжки в диапазоне 0x00..0x3F (комбинация флагов t_x502_pullups:
 *                              0x01=DI_H, 0x02=DI_L, 0x04=DI_SYN1, 0x08=DI_SYN2, 0x10=PULLDOWN_CONV_IN, 0x20=PULLDOWN_START_IN).
 * @return X502_ERR_OK (0) при успехе, либо X502_ERR_INVALID_OP_FOR_IFACE при наличии недопустимых битов (> 0x3F).
 */
int E502_StandSetPullups(E502_StandDevice *dev, uint32_t pullups_mask);

/**
 * @brief Транзакционно записывает текущую конфигурацию каналов и подтяжек в регистры ПЛИС (FPGA) модуля.
 *
 * Выполняет полную последовательность настройки в соответствии с документацией L-Card:
 * 1) X502_SetMode(hnd, X502_MODE_FPGA) ->
 * 2) X502_SetLChannelCount(hnd, lch_count) ->
 * 3) X502_SetLChannel(hnd, i, ...) для всех активных каналов 0 .. lch_count-1 ->
 * 4) X502_SetDigInPullup(hnd, pullups_mask) ->
 * 5) X502_Configure(hnd, 0).
 * При успешном завершении сбрасывает флаг dev->config_dirty = false.
 *
 * @param[in,out] dev  Указатель на контекст открытого устройства (dev->is_connected == true).
 * @return X502_ERR_OK (0) при успешной записи в ПЛИС, X502_ERR_DEVICE_NOT_OPENED если модуль не открыт,
 *         либо отрицательный код ошибки драйвера X502_ERR_*.
 */
int E502_StandApplyConfig(E502_StandDevice *dev);


/* ============================================================================
 * 3. Оперативный ввод-вывод (чтение кадров АЦП, выдача на ЦАП, индикация)
 * ============================================================================ */

/**
 * @brief Считывает один полный синхронный кадр напряжений АЦП по всем активным логическим каналам.
 *
 * Если перед чтением обнаружен несинхронизированный флаг dev->config_dirty == true, функция
 * автоматически вызывает E502_StandApplyConfig(dev). Затем выполняет асинхронный захват кадра
 * через X502_AsyncGetAdcFrame() с флагом X502_PROC_FLAGS_VOLT (перевод кодов АЦП в Вольты с учётом
 * заводской калибровки).
 *
 * @param[in,out] dev        Указатель на контекст подключённого устройства (не NULL).
 * @param[out]    volts_buf  Выходной буфер типа double размерностью не менее dev->lch_count элементов,
 *                           куда записываются измеренные напряжения в Вольтах для каналов 0 .. lch_count-1.
 * @param[in]     tout_ms    Таймаут ожидания готовности кадра АЦП в миллисекундах (рекомендуется 100..1000 мс).
 * @return X502_ERR_OK (0) при успешном чтении кадра, либо отрицательный код ошибки X502_ERR_*.
 */
int E502_StandReadAdcFrame(E502_StandDevice *dev, double *volts_buf, uint32_t tout_ms);

/**
 * @brief Устанавливает постоянное напряжение на выбранном выходе двухканального ЦАП.
 *
 * Проверяет корректность номера канала и принадлежность напряжения рабочему диапазону [-5.000; +5.000] В,
 * после чего передаёт значение в прибор через X502_AsyncOutDac() с флагами
 * X502_DAC_FLAGS_VOLT | X502_DAC_FLAGS_CALIBR и сохраняет уровень в dev->dac_volts[dac_ch].
 *
 * @param[in,out] dev     Указатель на контекст подключённого устройства (не NULL).
 * @param[in]     dac_ch  Номер канала ЦАП: X502_DAC_CH1 (0 — выход ЦАП1) или X502_DAC_CH2 (1 — выход ЦАП2).
 * @param[in]     volts   Конечное выходное напряжение в Вольтах в диапазоне от -5.0 до +5.0 В включительно.
 * @return X502_ERR_OK (0) при успешной выдаче напряжения, X502_ERR_INVALID_DAC_CHANNEL при неверном канале
 *         или выходе напряжения за пределы [-5.0; +5.0] В, либо X502_ERR_DEVICE_NOT_OPENED.
 */
int E502_StandWriteDac(E502_StandDevice *dev, uint32_t dac_ch, double volts);

/**
 * @brief Выполняет переключение (мигание) светодиода LED1 на лицевой панели модуля E-502.
 *
 * Используется для визуальной идентификации подключённого прибора и проверки работоспособности канала связи.
 *
 * @param[in,out] dev  Указатель на контекст подключённого устройства (не NULL).
 * @return X502_ERR_OK (0) при успешном выполнении команды X502_LedBlink(), либо код ошибки X502_ERR_*.
 */
int E502_StandBlinkLed(E502_StandDevice *dev);

/**
 * @brief Возвращает человекочитаемое строковое описание последней ошибки, сохранённой в dev->last_error.
 *
 * @param[in] dev  Указатель на контекст устройства (при передаче NULL возвращает "Invalid device pointer (NULL)").
 * @return Указатель на статическую нуль-терминированную строку с описанием кода ошибки из X502_GetErrorString().
 */
const char* E502_StandGetErrorStr(const E502_StandDevice *dev);

#endif /* E502_CTRL_H */
